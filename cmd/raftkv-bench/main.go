// Command raftkv-bench measures a real cluster: replicas run in one process
// but talk over loopback TCP and persist to disk with fsync, so the numbers
// include serialization, the network stack and durable writes.
//
//	raftkv-bench -mode all -out bench/results
//
// Experiments:
//
//	throughput  ops/s and latency vs client count, 3 vs 5 replicas
//	failover    time from killing the leader to the next successful write,
//	            for several election-timeout ranges, plus how many
//	            unnecessary elections each range causes under load
//	batching    baseline vs + batching vs + group commit
package main

import (
	"flag"
	"fmt"
	"log"
	"math/rand/v2"
	"net"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"sync"
	"sync/atomic"
	"time"

	"github.com/Navneesh004/raftkv/kv"
	"github.com/Navneesh004/raftkv/node"
	"github.com/Navneesh004/raftkv/raft"
)

var (
	outDir   = flag.String("out", "bench/results", "output directory for CSV, SVG and summary")
	mode     = flag.String("mode", "all", "all | throughput | failover | batching")
	duration = flag.Duration("duration", 5*time.Second, "measurement time per throughput point")
	trials   = flag.Int("trials", 50, "leader kills per election-timeout setting")
	noSync   = flag.Bool("nosync", false, "disable fsync (shows how much durability costs)")
)

func main() {
	flag.Parse()
	if err := os.MkdirAll(*outDir, 0o755); err != nil {
		log.Fatal(err)
	}
	var summary strings.Builder
	fmt.Fprintf(&summary, "# Benchmark results\n\nGenerated by `raftkv-bench` on %s. fsync: %v. "+
		"Replicas run in one process over loopback TCP with on-disk state.\n\n", time.Now().Format("2006-01-02"), !*noSync)
	if *mode == "all" || *mode == "throughput" {
		benchThroughput(&summary)
	}
	if *mode == "all" || *mode == "failover" {
		benchFailover(&summary)
	}
	if *mode == "all" || *mode == "batching" {
		benchBatching(&summary)
	}
	path := filepath.Join(*outDir, "summary.md")
	if err := os.WriteFile(path, []byte(summary.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Println(summary.String())
	log.Printf("wrote %s", path)
}

// --- cluster management -------------------------------------------------------

type cluster struct {
	addrs []string
	cfgs  []node.Config
	nodes []*node.Node
	dir   string
}

func startCluster(n int, rc raft.Config) *cluster {
	dir, err := os.MkdirTemp("", "raftkv-bench-")
	if err != nil {
		log.Fatal(err)
	}
	c := &cluster{dir: dir, nodes: make([]*node.Node, n)}
	lns := make([]net.Listener, n)
	for i := range lns {
		if lns[i], err = net.Listen("tcp", "127.0.0.1:0"); err != nil {
			log.Fatal(err)
		}
		c.addrs = append(c.addrs, lns[i].Addr().String())
	}
	for i := 0; i < n; i++ {
		cfg := node.Config{
			ID: i, Peers: c.addrs, DataDir: filepath.Join(dir, fmt.Sprint(i)),
			MaxRaftState: 64 << 10, Raft: rc, NoSync: *noSync, ListenAddr: c.addrs[i],
		}
		c.cfgs = append(c.cfgs, cfg)
		cfg.Listener = lns[i]
		if c.nodes[i], err = node.Start(cfg); err != nil {
			log.Fatal(err)
		}
	}
	c.leader()
	return c
}

func (c *cluster) kill(i int) {
	c.nodes[i].Stop()
	c.nodes[i] = nil
}

func (c *cluster) restart(i int) {
	var err error
	for try := 0; try < 50; try++ {
		if c.nodes[i], err = node.Start(c.cfgs[i]); err == nil {
			return
		}
		time.Sleep(20 * time.Millisecond) // port may linger briefly
	}
	log.Fatal(err)
}

func (c *cluster) leader() int {
	for iter := 0; iter < 500; iter++ {
		for i, n := range c.nodes {
			if n != nil && n.Status().Role == "leader" {
				return i
			}
		}
		time.Sleep(10 * time.Millisecond)
	}
	log.Fatal("no leader")
	return -1
}

func (c *cluster) stop() {
	for _, n := range c.nodes {
		if n != nil {
			n.Stop()
		}
	}
	os.RemoveAll(c.dir)
}

func (c *cluster) clerk() *kv.Clerk { return kv.MakeClerk(node.Endpoints(c.addrs, 2*time.Second)) }

// --- load ----------------------------------------------------------------------

type loadResult struct {
	opsPerSec float64
	p50, p99  time.Duration
}

// load runs `clients` closed-loop clients doing 64-byte Puts on random keys.
func load(c *cluster, clients int, d time.Duration) loadResult {
	value := strings.Repeat("v", 64)
	var stop atomic.Bool
	var mu sync.Mutex
	var lats []time.Duration
	var wg sync.WaitGroup
	// Warm up connections before measuring.
	c.clerk().Put("warmup", "x")
	start := time.Now()
	for i := 0; i < clients; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			ck := c.clerk()
			var local []time.Duration
			for !stop.Load() {
				t0 := time.Now()
				ck.Put(fmt.Sprintf("k%d", rand.IntN(1000)), value)
				local = append(local, time.Since(t0))
			}
			mu.Lock()
			lats = append(lats, local...)
			mu.Unlock()
		}()
	}
	time.Sleep(d)
	stop.Store(true)
	wg.Wait()
	elapsed := time.Since(start)
	sort.Slice(lats, func(i, j int) bool { return lats[i] < lats[j] })
	return loadResult{
		opsPerSec: float64(len(lats)) / elapsed.Seconds(),
		p50:       pct(lats, 50),
		p99:       pct(lats, 99),
	}
}

func pct(sorted []time.Duration, p int) time.Duration {
	if len(sorted) == 0 {
		return 0
	}
	return sorted[(len(sorted)-1)*p/100]
}

func ms(d time.Duration) float64 { return float64(d) / float64(time.Millisecond) }

func writeCSV(name string, header string, rows []string) {
	data := header + "\n" + strings.Join(rows, "\n") + "\n"
	if err := os.WriteFile(filepath.Join(*outDir, name), []byte(data), 0o644); err != nil {
		log.Fatal(err)
	}
}

func writeSVG(name, svg string) {
	if err := os.WriteFile(filepath.Join(*outDir, name), []byte(svg), 0o644); err != nil {
		log.Fatal(err)
	}
}

// --- experiments ---------------------------------------------------------------

func benchThroughput(sum *strings.Builder) {
	clientCounts := []int{1, 4, 16, 64}
	sizes := []int{3, 5}
	cats := make([]string, len(clientCounts))
	for i, c := range clientCounts {
		cats[i] = fmt.Sprint(c)
	}
	var tput, p50s []series
	var rows []string
	fmt.Fprintf(sum, "## Throughput and latency: 3 vs 5 replicas\n\n| replicas | clients | ops/s | p50 latency | p99 latency |\n|---|---|---|---|---|\n")
	for _, n := range sizes {
		c := startCluster(n, raft.DefaultConfig())
		ts := series{name: fmt.Sprintf("%d replicas", n)}
		ls := series{name: fmt.Sprintf("%d replicas", n)}
		for _, cl := range clientCounts {
			r := load(c, cl, *duration)
			log.Printf("throughput: %d replicas, %2d clients: %7.0f ops/s  p50 %v  p99 %v", n, cl, r.opsPerSec, r.p50, r.p99)
			ts.values = append(ts.values, r.opsPerSec)
			ls.values = append(ls.values, ms(r.p50))
			rows = append(rows, fmt.Sprintf("%d,%d,%.1f,%.3f,%.3f", n, cl, r.opsPerSec, ms(r.p50), ms(r.p99)))
			fmt.Fprintf(sum, "| %d | %d | %.0f | %.2f ms | %.2f ms |\n", n, cl, r.opsPerSec, ms(r.p50), ms(r.p99))
		}
		c.stop()
		tput = append(tput, ts)
		p50s = append(p50s, ls)
	}
	writeCSV("throughput.csv", "replicas,clients,ops_per_sec,p50_ms,p99_ms", rows)
	writeSVG("throughput.svg", lineChart("Throughput vs concurrent clients", "concurrent clients", "operations / second", cats, tput, "%.0f"))
	writeSVG("latency.svg", lineChart("Median write latency vs concurrent clients", "concurrent clients", "p50 latency (ms)", cats, p50s, "%.1f"))
	sum.WriteString("\n![throughput](throughput.svg)\n\n![latency](latency.svg)\n\n")
}

func benchFailover(sum *strings.Builder) {
	settings := [][2]time.Duration{
		{100 * time.Millisecond, 200 * time.Millisecond},
		{150 * time.Millisecond, 300 * time.Millisecond},
		{300 * time.Millisecond, 600 * time.Millisecond},
		{600 * time.Millisecond, 1200 * time.Millisecond},
	}
	var cats []string
	med := series{name: "median"}
	p95 := series{name: "95th percentile"}
	var rows []string
	fmt.Fprintf(sum, "## Leader failover vs election timeout\n\nThe leader is killed (connections dropped, process state gone) %d times per setting; "+
		"failover is the time until a client's next write succeeds. Heartbeats are every 50 ms in every setting. "+
		"*Unneeded elections* counts term changes during 10 s of steady load with no failures — false alarms by the failure detector.\n\n"+
		"| election timeout | median failover | p95 | max | unneeded elections / 10 s |\n|---|---|---|---|---|\n", *trials)
	for _, s := range settings {
		rc := raft.DefaultConfig()
		rc.ElectionTimeoutMin, rc.ElectionTimeoutMax = s[0], s[1]
		label := fmt.Sprintf("%d–%d ms", s[0].Milliseconds(), s[1].Milliseconds())
		cats = append(cats, label)
		c := startCluster(3, rc)

		// False alarms: elections during steady load with nothing failing.
		l := c.leader()
		term0 := c.nodes[l].Status().Term
		load(c, 16, 10*time.Second)
		maxTerm := 0
		for _, n := range c.nodes {
			if t := n.Status().Term; t > maxTerm {
				maxTerm = t
			}
		}
		spurious := maxTerm - term0

		var times []time.Duration
		for t := 0; t < *trials; t++ {
			l := c.leader()
			ck := c.clerk()
			ck.Put("probe", "warm")
			c.kill(l)
			t0 := time.Now()
			ck.Put("probe", fmt.Sprint(t))
			times = append(times, time.Since(t0))
			c.restart(l)
			time.Sleep(time.Duration(float64(s[1]) * 1.5)) // let the restarted replica rejoin
		}
		c.stop()
		sort.Slice(times, func(i, j int) bool { return times[i] < times[j] })
		m, p, mx := pct(times, 50), pct(times, 95), times[len(times)-1]
		log.Printf("failover %s: median %v p95 %v max %v, unneeded elections %d", label, m, p, mx, spurious)
		med.values = append(med.values, ms(m))
		p95.values = append(p95.values, ms(p))
		for i, d := range times {
			rows = append(rows, fmt.Sprintf("%d,%d,%d,%.3f", s[0].Milliseconds(), s[1].Milliseconds(), i, ms(d)))
		}
		fmt.Fprintf(sum, "| %s | %.0f ms | %.0f ms | %.0f ms | %d |\n", label, ms(m), ms(p), ms(mx), spurious)
	}
	writeCSV("failover.csv", "timeout_min_ms,timeout_max_ms,trial,failover_ms", rows)
	writeSVG("failover.svg", barChart("Failover time after killing the leader", "election timeout range", "time to next successful write (ms)", cats, []series{med, p95}, "%.0f"))
	sum.WriteString("\n![failover](failover.svg)\n\n")
}

func benchBatching(sum *strings.Builder) {
	const clients = 64
	var cats []string
	tp := series{name: "throughput"}
	var rows []string
	fmt.Fprintf(sum, "## Optimisations: batching and group commit\n\n3 replicas, %d clients, applied one at a time:\n\n"+
		"- **baseline**: each AppendEntries carries one entry, and the leader fsyncs every entry inside `Start()` while holding the lock.\n"+
		"- **+ batching**: every entry that arrived while the previous AppendEntries was in flight goes in the next one, so followers pay one fsync per batch.\n"+
		"- **+ group commit**: the leader also stops fsyncing inside `Start()`; a syncer goroutine fsyncs all entries appended since its last write in one go, outside the lock, "+
		"and the leader counts itself toward a majority only for entries already on disk.\n\n"+
		"| configuration | ops/s | p50 latency | p99 latency |\n|---|---|---|---|\n", clients)
	var base float64
	configs := []struct {
		label       string
		max         int
		groupCommit bool
	}{{"baseline", 1, false}, {"+ batching", 0, false}, {"+ group commit", 0, true}}
	for i, b := range configs {
		rc := raft.DefaultConfig()
		rc.MaxEntriesPerRPC = b.max
		rc.DisableGroupCommit = !b.groupCommit
		c := startCluster(3, rc)
		r := load(c, clients, 2**duration)
		c.stop()
		log.Printf("optimisation %s: %.0f ops/s p50 %v p99 %v", b.label, r.opsPerSec, r.p50, r.p99)
		cats = append(cats, b.label)
		tp.values = append(tp.values, r.opsPerSec)
		rows = append(rows, fmt.Sprintf("%s,%d,%v,%.1f,%.3f,%.3f", b.label, b.max, b.groupCommit, r.opsPerSec, ms(r.p50), ms(r.p99)))
		fmt.Fprintf(sum, "| %s | %.0f | %.2f ms | %.2f ms |\n", b.label, r.opsPerSec, ms(r.p50), ms(r.p99))
		if i == 0 {
			base = r.opsPerSec
		}
	}
	if base > 0 {
		fmt.Fprintf(sum, "\nTogether, the two optimisations raise throughput **%.1f×** over the baseline.\n", tp.values[len(tp.values)-1]/base)
	}
	writeCSV("optimisations.csv", "config,max_entries_per_rpc,group_commit,ops_per_sec,p50_ms,p99_ms", rows)
	writeSVG("optimisations.svg", barChart(fmt.Sprintf("Throughput as each optimisation is added (3 replicas, %d clients)", clients), "", "operations / second", cats, []series{tp}, "%.0f"))
	sum.WriteString("\n![optimisations](optimisations.svg)\n")
}
